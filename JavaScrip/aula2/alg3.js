//Exemplo de operadores matemáticos 

let a = 10;
let b = 5;

//Adição 
let soma = a + b;
console.log("Soma:" + soma);

//Subtração 
let Subtração = a - b;
console.log("Subtração: " + subtração);


//Multiplicação
let Multiplicação = a * b;
console.log("Multiplicação: " + multiplicação);

//Divisão
let Divisão = a / b;
console.log("Divisão:" + divisão);
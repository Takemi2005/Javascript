// laços de repetição
//  for
//  for (condição) {
//  bloco de código 
//}

for (let i = 10; i <= 20; i++) {
    console.log(i);
}


for (let i = 20; i >= 10; i--) {
    console.log(i);
}


for (let i = 0; i <= 100; i += 10) {
    console.log(i);
}

